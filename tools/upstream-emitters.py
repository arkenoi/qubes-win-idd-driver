#!/usr/bin/env python3
"""Which declared-level log lines come from VENDORED code we do not maintain.

THE RULE (owner, 2026-10-18): "if emitter is noisy upstream, you exclude it from gate, using to
augment the diagnosis, not as acceptance criteria."

So this is not a disposition and not a ledger row. A line from a library we vendor read-only is
printed for diagnosis and does not decide acceptance, because we cannot fix it and a receipt we
write for it is a rationale, not a receipt.

THE TRAP THIS EXISTS TO AVOID. upstream/ro/ holds the upstream copies of OUR OWN FORKS -
qubes-gui-agent-windows is forked as agent/, qubes-core-agent-windows as core-agent/. Their
functions (WatchForEvents, CaptureThread, Init, GetWindowData, HandleConfigure, SetSeamlessMode...)
emit in BOTH trees, so a naive "is it under upstream/ro" test would silence our own code - exactly
the concealment the gate exists to prevent. The answer is a SET DIFFERENCE: a function is upstream
only when it emits a declared level in vendored code and emits NOWHERE in our own tree.

Output: one line per function, `<function>\t<vendored file that emits it>`, so every exclusion
carries the path it came from. Regenerate with:  tools/upstream-emitters.py --write
"""
import os
import re
import sys

VENDORED = "upstream/ro"
OURS = ("agent", "core-agent", "guest", "mgmt", "tools", "packaging")
OUT = "mgmt/harness/upstream-emitters.txt"

# A declared level in the Windows log format is written by these. LogInfo/LogDebug are not graded,
# so a function that only ever emits those is not interesting here.
EMIT = re.compile(r"\b(?:LogWarning|LogError|win_perror2?|PlatLogWarning|PlatLogError)\s*\(")
# A function DEFINITION, not a call: the name sits before "(" on a line that is not a statement.
DEFN = re.compile(r"^[A-Za-z_][\w \t\*]*?\b([A-Za-z_]\w+)\s*\([^;]*$")
KEYWORDS = ("if", "for", "while", "switch", "return", "else", "do", "sizeof", "case")


def emitters(roots):
    """{function: set(files)} for functions whose body emits a declared level."""
    found = {}
    for root in roots:
        if not os.path.isdir(root):
            continue
        for dirpath, _, names in os.walk(root):
            for name in names:
                if not name.endswith((".c", ".cpp", ".cxx")):
                    continue
                path = os.path.join(dirpath, name)
                try:
                    lines = open(path, encoding="utf-8", errors="replace").read().splitlines()
                except OSError:
                    continue
                cur = None
                for line in lines:
                    stripped = line.strip()
                    m = DEFN.match(line.rstrip())
                    if m and not stripped.startswith(KEYWORDS) and m.group(1) not in KEYWORDS:
                        cur = m.group(1)
                    if cur and EMIT.search(line):
                        found.setdefault(cur, set()).add(path)
    return found


def main():
    vend = emitters([VENDORED])
    ours = emitters(list(OURS))
    # THE DIFFERENCE IS THE WHOLE POINT. A function our tree also emits from is OURS, whatever
    # upstream does with the same name.
    only = {f: sorted(p)[0] for f, p in vend.items() if f not in ours}
    rows = ["%s\t%s" % (f, only[f]) for f in sorted(only)]
    header = [
        "# GENERATED by tools/upstream-emitters.py - do not hand-edit.",
        "# Functions that emit a declared ERROR/WARNING in code we vendor READ-ONLY and that emit",
        "# nowhere in agent/ core-agent/ guest/ mgmt/ tools/ packaging/. tools/sweep-gate.sh prints",
        "# their lines for diagnosis and does not count them toward acceptance (owner 2026-10-18).",
        "# %d of %d vendored emitters; the other %d also emit in our own tree and stay GRADED." % (
            len(only), len(vend), len(vend) - len(only)),
    ]
    text = "\n".join(header + rows) + "\n"
    if "--write" in sys.argv:
        open(OUT, "w", encoding="utf-8").write(text)
        print("wrote %s: %d upstream-only emitter(s), %d kept graded as ours" % (
            OUT, len(only), len(vend) - len(only)))
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
